    def __init__(self,ledger):super().__init__();self.ledger=ledger;self.records={}
    def __setitem__(self,key,value):
        super().__setitem__(key,value)
        if len(self.records)<65536 or key in self.records:
            best_effort(self.records.__setitem__,key,dict(action_id=key,lane=value.get('lane'),execution_id=value.get('execution_id'),
                reserved_at=safe_now(self.ledger),granted_at=None,released_at=None,clock_id=CLOCK_ID,epoch=self.ledger.epoch))
