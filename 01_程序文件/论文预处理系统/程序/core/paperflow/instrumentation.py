def length_evidence(value):
    if not isinstance(value,dict):return None
    records=[];source=value.get('records')
    if not isinstance(source,list):return None
    affected=[row for row in source if isinstance(row,dict) and row.get('issues')]
    for row in affected[:4]:
        item={k:row[k] for k in ('model_tokens','model_budget','cl100k_tokens','cl100k_limit')
            if type(row.get(k)) is int and 0<=row[k]<10**9}
        for key in ('record_id','record_type','role','specialty_code','path'):
            text=row.get(key)
            if isinstance(text,str) and re.fullmatch(r'[A-Za-z0-9_.:-]{1,80}',text):item[key]=text
        item['issues']=[x for x in row['issues'] if x in {'embedding_model_length','embedding_pipeline_length',
            'embedding_adapter_length','embedding_policy_unverified','embedding_path_unverified','embedding_counter_unverified'}]
        records.append(item)
    fingerprint=value.get('rule_fingerprint')
    return dict(rule_fingerprint=fingerprint if isinstance(fingerprint,str) and re.fullmatch('[a-f0-9]{64}',fingerprint) else None,
        records=records,records_truncated=len(affected)>4,affected_count=len(affected))


def diagnostic(exc,*,stage=None,identity=None):
    """Structural traceback only: no source line, message, arguments, or locals.

    Arbitrary exception messages can contain complete manuscripts or credentials;
    regex redaction cannot prove their absence. The sanitized repr explicitly
    declares that the message was removed, while preserving type/code/frames.
    """
    try:
        frames=[dict(file=Path(f.filename).name,line=f.lineno,function=f.name)
                for f in traceback.extract_tb(exc.__traceback__)[-8:]]
        message=str(exc);safe=message in SAFE_MESSAGES
        status=getattr(exc,'status_code',None)
        code=getattr(exc,'service_code',None);check=getattr(exc,'check',None)
        return dict(type=type(exc).__name__,repr=f'{type(exc).__name__}({message!r})' if safe else f'{type(exc).__name__}(<message redacted>)',
            repr_redacted=not safe,message_length=len(message),message_truncated=len(message)>240,
            http_status=status if type(status) is int and 100<=status<=599 else None,
            service_code=code if code in {'AUTH','INVALID_REQUEST','MISSING_CREDENTIAL','INVALID_CREDENTIAL','RATE_LIMIT','CONTEXT_LENGTH_EXCEEDED'} else None,
            check=check if check in {'embedding_length','missing_files','body_loss','privacy','identity','wrong_library'} else None,
            length_evidence=length_evidence(getattr(exc,'evidence',None)),
            traceback=frames,traceback_truncated=len(traceback.extract_tb(exc.__traceback__))>8,
            stage=stage,sqlite_errorcode=getattr(exc,'sqlite_errorcode',None),
            sqlite_errorname=getattr(exc,'sqlite_errorname',None),
            identity={k:v for k,v in (identity or {}).items() if k in
                ('attempt_id','action_id','job_id','task_id','manifest_sha256','specialty_code','execution_id','epoch')})
    except BaseException:
        return dict(type=type(exc).__name__,repr='<diagnostic unavailable>',traceback=[],metrics_complete=False)


def best_effort(function,*args,**kwargs):
    try:return function(*args,**kwargs)
    except BaseException:return None


def slot_event(owner,lane,event,*args):
    try:return getattr(getattr(owner,lane),event)(*args)
    except BaseException:return None


def safe_now(recorder):
    try:return recorder.clock()
    except BaseException:
        try:recorder.complete=False
        except BaseException:pass
        return time.monotonic()


@contextmanager
def using(recorder):
    token=CURRENT.set(recorder)
    try:yield recorder
    finally:CURRENT.reset(token)


@contextmanager
def safe_span(recorder,label,**metadata):
    manager=None;entered=False
    try:
        manager=recorder.span(label,**metadata) if recorder else None
        value=manager.__enter__() if manager else None;entered=manager is not None
    except BaseException:
        value=None
        try:recorder.complete=False
        except BaseException:pass
    try:yield value
    except BaseException as exc:
        if entered:best_effort(manager.__exit__,type(exc),exc,exc.__traceback__)
        raise
    else:
        if entered:best_effort(manager.__exit__,None,None,None)


@contextmanager
def timed(label,**metadata):
    with safe_span(CURRENT.get(),label,**metadata) as value:yield value


def measured(label):
    def decorate(function):
        @wraps(function)
        def wrapped(*args,**kwargs):
            with timed(label):return function(*args,**kwargs)
        return wrapped
    return decorate


class Recorder:
    def __init__(self,*,clock=None,epoch=None,enabled=True,max_spans=2048):
        self.clock=clock or time.monotonic;self.clock_id=CLOCK_ID;self.epoch=epoch
        self.complete=True
        self.enabled=enabled and os.environ.get('PAPERFLOW_METRICS','1')!='0';self.started=safe_now(self);self.spans=[];self.stack=[]
        self.observations=[];self.poll_times=[];self.stages=[]
        self.polls=[]
        self.max_spans=max_spans;self.span_overflow=False;self.skipped_span_count=0
        self.prior_stages={};self.prior_history_verified=False

    def _record_span(self,record):
        if len(self.spans)>=self.max_spans:
            self.span_overflow=True;self.complete=False;self.skipped_span_count+=1
        else:self.spans.append(record)

    def _overflow(self,elapsed):
        return dict(clock_id=self.clock_id,epoch=self.epoch,elapsed_seconds=max(0,elapsed),
            metrics_complete=False,span_overflow=True,span_limit=self.max_spans,
            recorded_span_count=len(self.spans),skipped_span_count=self.skipped_span_count)

    @contextmanager
    def use(self):
        token=CURRENT.set(self)
        try:yield self
        finally:CURRENT.reset(token)

    @contextmanager
    def span(self,label,**metadata):
        if not self.enabled:yield None;return
        record=dict(label=label,start=self.clock(),end=None,depth=len(self.stack),**metadata)
        self._record_span(record);self.stack.append(record)
        try:yield record
        finally:
            record['end']=self.clock();self.stack.pop()

    def partition(self,outer):
        if outer is None:return dict(metrics_complete=False,elapsed_seconds=None)
        start,end=outer['start'],outer['end']
        end=self.clock() if end is None else end
        if self.span_overflow:
            return dict(self._overflow(end-start),exclusive_seconds={},correction_inner_seconds={},business_seconds={},
                residual_seconds=max(0,end-start))
        children=[x for x in self.spans if x is not outer and x['start']>=start and
            x['start']<=end and x['depth']>outer['depth']]
        points=sorted({start,end,*[max(start,min(end,x[k] if x[k] is not None else end))
            for x in children for k in ('start','end')]})
        totals=defaultdict(float);inner=defaultdict(float)
        for a,b in zip(points,points[1:]):
            active=[x for x in children if x['start']<=a and (x['end'] if x['end'] is not None else end)>=b]
            leaves=[x for x in active if x['label'] not in ('permit_hold','stage','correction_rerun') and not x['label'].startswith('business:')]
            leaf=max(leaves,key=lambda x:x['depth']) if leaves else None
            correction=any(x['label']=='correction_rerun' for x in active)
            label='correction_rerun' if correction else leaf['label'] if leaf else outer.get('default_label','residual')
            totals[label]+=b-a
            if correction:inner[leaf['label'] if leaf and leaf['label']!='correction_rerun' else 'residual']+=b-a
        elapsed=max(0,end-start);residual=totals.pop('residual',0)
        business=defaultdict(float)
        for a,b in zip(points,points[1:]):
            active=[x for x in children if x['label'].startswith('business:') and x['start']<=a and (x['end'] if x['end'] is not None else end)>=b]
            if active:business[max(active,key=lambda x:x['depth'])['label'].removeprefix('business:')]+=b-a
        return dict(clock_id=self.clock_id,epoch=self.epoch,elapsed_seconds=elapsed,business_seconds=dict(business),
            exclusive_seconds=dict(totals),correction_inner_seconds=dict(inner),residual_seconds=residual,
            metrics_complete=self.complete and outer['end'] is not None and residual<=max(.05,.01*elapsed))

    def interval(self,label,start,end,**metadata):
        if self.enabled:self._record_span(dict(label=label,start=start,end=end,depth=len(self.stack),**metadata))

    def summary(self):
        elapsed=self.clock()-self.started
        if self.span_overflow:
            return dict(self._overflow(elapsed),stage_visit_count=len(self.stages),stages_truncated=True,
                five_stage_elapsed_seconds=None,five_stage_elapsed_complete=False)
        spans=tuple(self.spans);now=self.started+elapsed
        points=sorted({self.started,now,*[max(self.started,min(now,x[k] if x[k] is not None else now))
            for x in spans for k in ('start','end')]})
        account=defaultdict(float);business=defaultdict(float)
        for a,b in zip(points,points[1:]):
            active=[x for x in spans if x['start']<=a and (x['end'] if x['end'] is not None else now)>=b]
            holds=[x for x in active if x['label']=='permit_hold' and x.get('kind','').startswith('rag_')]
            waits=[x for x in active if x['label']=='permit_wait' and x.get('kind','').startswith('rag_')]
            category=('rag_hold' if holds else 'rag_permit_wait' if waits else 'resource_wait'
                if any(x['label']=='resource_wait' for x in active) else 'outside_processing')
            account[category]+=b-a
            business_active=[x for x in active if x['label'].startswith('business:')]
            if business_active:
                business[max(business_active,key=lambda x:x['depth'])['label'].removeprefix('business:')]+=b-a
        graph=[x for x in spans if x['label']=='graph']
        stage_window=five_stage_window(self.stages,self.clock_id,self.epoch)
        return dict(clock_id=self.clock_id,epoch=self.epoch,elapsed_seconds=elapsed,
            metrics_complete=self.complete
                and all(stage.get('metrics_complete') is True for stage in self.stages)
                and all(span['end'] is not None for span in spans)
                and all(poll.get('metrics_complete') is True for poll in self.polls),
            stages=[compact_stage_timing(stage,include_clock=False,inherited_clock=self.clock_id,inherited_epoch=self.epoch) for stage in self.stages],
            business_seconds=dict(business),business_view_additive_to_attempt=False,
            stages_truncated=False,stage_visit_count=len(self.stages),server_observations_available=bool(self.observations),
            attempt_exclusive_seconds=dict(account),attempt_residual_seconds=elapsed-sum(account.values()),
            graph_elapsed_seconds=sum((x['end'] or now)-x['start'] for x in graph) if graph else None,
            five_stage_seconds=sum(x['elapsed_seconds'] for x in self.stages if type(x.get('elapsed_seconds')) in (int,float)) if self.stages else None,
            **stage_window)


def compact_stage_timing(fact,*,include_clock=True,inherited_clock=None,inherited_epoch=None):
    """Persist the full accounting leaves, dropping only redundant envelope data."""
    keys=('stage','business_stage','stage_invocation_id','started_at','ended_at','elapsed_seconds','exclusive_seconds','correction_inner_seconds',
        'business_seconds','residual_seconds','metrics_complete','disposition','input_fingerprint','outcome',
        'coverage','prefix_metrics_complete')
    if include_clock or fact.get('clock_id')!=inherited_clock or fact.get('epoch')!=inherited_epoch:keys+=('clock_id','epoch')
    result={key:fact[key] for key in keys if key in fact}
    if result.get('business_stage')==result.get('stage'):result.pop('business_stage',None)
    if not include_clock and result.get('coverage')=='stage_terminal':result.pop('coverage',None)
    return result


def five_stage_window(stages,clock_id,epoch):
    expected={'round1','round2','round3_assets','round3_redact','round3_chunk'}
    rows=[stage for stage in stages if (stage.get('business_stage') or stage.get('stage')) in expected]
    present={stage.get('business_stage') or stage.get('stage') for stage in rows}
    qualified=bool(rows) and expected<=present and all(
        stage.get('clock_id')==clock_id and stage.get('epoch')==epoch and stage.get('coverage')!='through_action_end'
        and all(type(stage.get(key)) in (int,float) and math.isfinite(stage[key]) for key in ('started_at','ended_at'))
        and stage['ended_at']>=stage['started_at'] for stage in rows)
    return dict(five_stage_elapsed_seconds=max(stage['ended_at'] for stage in rows)-min(stage['started_at'] for stage in rows)
            if qualified else None,five_stage_elapsed_complete=qualified)


def interruption_account(records):
    """Attribution, not an assertion that all earlier work was wasted."""
    interrupted={};consumed=redo=unknown=0.0;missing=0;cache=checkpoint=0.0
    for row in records:
        if row.get('stage')!='round1':continue
        seconds=row.get('elapsed_seconds')
        if type(seconds) not in (int,float) or not math.isfinite(seconds) or seconds<0:missing+=1;continue
        fingerprint=row.get('input_fingerprint')
        key=(row.get('task_id'),row.get('stage'),fingerprint) if fingerprint else None
        disposition=row.get('disposition')
        if disposition=='cache_hit':cache+=seconds;continue
        if disposition=='checkpoint_skip':checkpoint+=seconds;continue
        if row.get('outcome') in ('stopped','interrupted','failed'):
            consumed+=seconds
            if key:interrupted[key]=row.get('attempt_id')
        elif key in interrupted and row.get('attempt_id')!=interrupted[key] and disposition in (
                'first_execution','recompute','technical_correction','execution_history_unknown'):redo+=seconds
        else:unknown+=seconds
    return dict(prior_interrupted_consumed_seconds=consumed,verified_same_stage_redo_seconds=redo,
        unknown_causality_seconds=unknown,cache_hit_seconds=cache,checkpoint_skip_seconds=checkpoint,
        missing_duration_count=missing,waste_seconds=None)


def stage_disposition(recorder,task,stage,result):
    if result.get('_cache_hit'):return 'cache_hit'
    if stage=='repair' or task.get('preparation_length_repair'):return 'technical_correction'
    prior=recorder.prior_stages.get(stage,{})
    local=any(x.get('stage')==stage and x.get('disposition') not in ('cache_hit','checkpoint_skip') for x in recorder.stages)
    if prior.get('confirmed') or local or task.get('stage_outputs',{}).get(stage):return 'recompute'
    if prior.get('unknown') or not recorder.prior_history_verified:return 'execution_history_unknown'
    return 'first_execution'


