class SlotLedger:
    """Append-only event inbox; snapshot replays a private copy, no shared integral.

    Grant/release callers already hold the relevant business lock. Gate samples
    arrive from the scheduler. Atomic append avoids introducing a telemetry lock
    or racing mutable integral totals across these existing threads.
    """
    def __init__(self,capacity=64,*,clock=None,epoch=None,max_events=65536):
        self.capacity=capacity;self.clock=clock or time.monotonic;self.epoch=epoch
        self.started=self.clock();self.events=deque(maxlen=max_events);self.active={};self.boundaries={}
        self.max_events=max_events;self.truncated_at=None;self.first_event=None
        self.reasons=();self.supply=None;self.paused=False;self.complete=True
    def _append(self,operation,*args,**kwargs):
        now=self.clock();event=(now,operation,args,kwargs)
        if self.truncated_at is None and len(self.events)<self.max_events:
            self.events.append(event)
            if self.first_event is None:self.first_event=event
        else:
            if self.truncated_at is None:self.truncated_at=now
            self.complete=False
        return now
    def observe(self,*,reasons=(),paused=False,supply_demand=None,held_blocking=False):
        self._append('observe',reasons=tuple(reasons),paused=paused,supply_demand=supply_demand,held_blocking=held_blocking)
        self.reasons=tuple(reasons);self.supply=supply_demand;self.paused=paused
    def grant(self,key):
        now=self._append('grant',key);self.active[key]=False
        self._mark(key,'grant',now)
    def release(self,key):
        now=self._append('release',key);self.active.pop(key,None)
        self._mark(key,'release',now)
    def held(self,key,value):
        self._append('held',key,value)
        if key in self.active:self.active[key]=bool(value)
    def _mark(self,key,event,now):
        if key in self.boundaries or len(self.boundaries)<self.max_events:self.boundaries.setdefault(key,{})[event]=now
        else:self.complete=False
    def mark(self,key,event):self._mark(key,event,self.clock())
    def snapshot(self):
        events=tuple(self.events);now=self.clock();at=self.started
        cutoff=min(now,self.truncated_at) if self.truncated_at is not None else now
        if events and events[0] is not self.first_event:
            # A deque race at the hard bound cannot produce invented history.
            events=();cutoff=self.started;self.complete=False
        integral=_SlotIntegral(self.capacity,clock=lambda:at,epoch=self.epoch)
        for at,operation,args,kwargs in sorted(events,key=lambda event:event[0]):
            getattr(integral,operation)(*args,**kwargs)
        at=cutoff;result=integral.snapshot()
        unknown=max(0,now-cutoff)
        result.update(observed_window_seconds=result['window_seconds'],window_seconds=now-self.started,
            unobserved_seconds=unknown,event_count=len(events),event_limit=self.max_events,
            capacity_seconds=self.capacity*(now-self.started),
            residual_slot_seconds=result['residual_slot_seconds']+self.capacity*unknown,
            conservation_residual_slot_seconds=result['conservation_residual_slot_seconds']+self.capacity*unknown)
        if unknown:
            result['full_rate_all']=None;result['full_rate_eligible']=None
        result['metrics_complete']=result['metrics_complete'] and self.complete
        return result


